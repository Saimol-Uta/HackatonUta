// Builds supabase/seed.sql from the scraped course listing.
// Usage: pnpm seed [path/to/cursos_fisei.csv]
import { readFileSync, writeFileSync } from "node:fs";
import { parseCoursesCsv } from "../src/core/catalog/parse-courses-csv.ts";

const input = process.argv[2] ?? "data/cursos_fisei.csv";
const output = "supabase/seed.sql";

const sql = (value: string | number | null): string =>
  value === null ? "null" : typeof value === "number" ? String(value) : `'${value.replaceAll("'", "''")}'`;

const courses = parseCoursesCsv(readFileSync(input, "utf8"));

const rows = courses.map(
  (c) => `  (${sql(c.slug)}, ${sql(c.name)}, ${sql(c.status)}, ${sql(c.trainingHours)}, ${sql(c.url)}, ${sql(c.imageUrl)})`,
);

writeFileSync(
  output,
  `-- Generated by scripts/build-course-seed.ts from ${input}. Do not edit by hand.
insert into public.courses (slug, name, status, training_hours, url, image_url) values
${rows.join(",\n")}
on conflict (slug) do update set
  name = excluded.name,
  status = excluded.status,
  training_hours = excluded.training_hours,
  url = excluded.url,
  image_url = excluded.image_url,
  updated_at = now();
`,
);

console.log(`Wrote ${courses.length} courses to ${output}`);
