// Builds supabase/seed.sql from the scraped course catalog.
// Usage: pnpm seed [path/to/cursos_fisei_completo.csv]
import { readFileSync, writeFileSync } from "node:fs";
import { parseCoursesCsv } from "../src/core/catalog/parse-courses-csv.ts";

const input = process.argv[2] ?? "data/cursos_fisei_completo.csv";
const output = "supabase/seed.sql";

const sql = (value: string | number | null | undefined): string =>
  value == null ? "null" : typeof value === "number" ? String(value) : `'${value.replaceAll("'", "''")}'`;

const courses = parseCoursesCsv(readFileSync(input, "utf8"));

const columns = [
  "slug",
  "name",
  "status",
  "training_hours",
  "url",
  "image_url",
  "full_title",
  "description",
  "objectives",
  "location",
  "organizers",
  "enrollment_start",
  "enrollment_end",
  "start_date",
  "end_date",
  "schedule",
  "modality",
  "certificate",
  "price_uta_student",
  "price_uta_staff",
  "price_public",
  "details_text",
];

const rows = courses.map((c) => {
  const d = c.details;
  const values = [
    c.slug,
    c.name,
    c.status,
    c.trainingHours,
    c.url,
    c.imageUrl,
    c.fullTitle,
    c.description,
    c.objectives,
    c.location,
    c.organizers,
    d?.enrollmentStart,
    d?.enrollmentEnd,
    d?.startDate,
    d?.endDate,
    d?.schedule,
    d?.modality,
    d?.certificate,
    d?.prices?.utaStudent,
    d?.prices?.utaStaff,
    d?.prices?.public,
    d?.text,
  ];
  return `  (${values.map(sql).join(", ")})`;
});

const updates = columns
  .filter((column) => column !== "slug")
  .map((column) => `  ${column} = excluded.${column},`)
  .join("\n");

writeFileSync(
  output,
  `-- Generated by scripts/build-course-seed.ts from ${input}. Do not edit by hand.
insert into public.courses (${columns.join(", ")}) values
${rows.join(",\n")}
on conflict (slug) do update set
${updates}
  updated_at = now();
`,
);

console.log(`Wrote ${courses.length} courses to ${output}`);
